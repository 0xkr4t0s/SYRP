//! B4 search and B5 `llms-<crate>.txt` slices over the fixture index (`tests/fixtures/demo.json`).

use std::path::Path;

use syrp_docgen::{ApiIndex, build_index, search, write_crate_slice};

fn index() -> ApiIndex {
    let fixture = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/demo.json");
    build_index(&[fixture]).expect("fixture parses")
}

#[test]
fn b4_search_ranks_name_then_alias_then_docs() {
    let index = index();
    let paths = |q: &str| {
        search(&index, q, 5)
            .iter()
            .map(|h| h.entry.path.clone())
            .collect::<Vec<_>>()
    };
    // Exact (case-insensitive) name matches first; equal scores sort by path.
    assert_eq!(paths("gain")[..2], ["demo::Gain", "demo::gain"]);
    assert_eq!(paths("gai")[..2], ["demo::Gain", "demo::gain"]);
    assert_eq!(paths("addNumbers"), ["demo::add"]);
    // A JUCE name finds the Rust item through its alias, whole or by last segment.
    assert_eq!(paths("juce::dsp::Gain")[0], "demo::Gain");
    assert_eq!(paths("AudioGain")[0], "demo::Gain");
    // Doc text matches rank below names; every term must match.
    assert_eq!(paths("iterable"), ["demo::Gain::apply"]);
    assert_eq!(paths("gain iterable"), ["demo::Gain::apply"]);
    assert!(paths("gain nonexistentword").is_empty());
    assert!(paths("   ").is_empty());
    assert_eq!(search(&index, "gain", 1).len(), 1);
    let hits = search(&index, "process", 10);
    assert!(hits.windows(2).all(|w| w[0].score >= w[1].score));
}

#[test]
fn b5_slice_fits_budget_and_lists_items() {
    let index = index();
    let full = write_crate_slice(&index, "demo", 100_000);
    assert!(full.starts_with("# demo\n\n> GENERATED by syrp-docgen"));
    let add = "- `pub fn add(a: u32, b: u32) -> u32` (demo::add) [alias: addNumbers]: Adds two numbers.\n";
    assert!(full.contains(add), "{full}");
    assert!(!full.contains("omitted"));
    // Top-level types come before their members.
    assert!(full.find("(demo::Gain)").unwrap() < full.find("(demo::Gain::new)").unwrap());
    for budget in [60, 120, 250] {
        let cut = write_crate_slice(&index, "demo", budget);
        assert!(
            cut.len().div_ceil(4) <= budget,
            "budget {budget}: {} bytes",
            cut.len()
        );
        assert!(
            cut.trim_end()
                .ends_with("more items omitted (token budget)"),
            "{cut}"
        );
    }
    assert_eq!(write_crate_slice(&index, "demo", 5), "");
    assert!(write_crate_slice(&index, "other-crate", 1000).contains("0 items"));
}
