#[test]
fn b4_check_refs_fails_on_paths_missing_from_the_index() {
    let spec = "## Behaviour\n- B1. Wraps `demo::Gain` and demo::Gian.\n- B2. Uses syrp_widgets_slider::Slider; see syrp::prelude::Thing.\n";
    let guide = "Call `demo::add()` or demo::sub::Missing::<u8>.\n";
    let dir = scratch("refs-bad", &[("spec.md", spec), ("guide.md", guide)]);
    let files = [dir.join("spec.md"), dir.join("guide.md")];
    let err = check_refs(&index(), &files).unwrap_err();
    assert_eq!(err.code().as_str(), "SYRP-DOC-0006");
    let DocError::UnresolvedRefs { refs } = &err else {
        panic!("{err}")
    };
    let found: Vec<(usize, &str)> = refs.iter().map(|r| (r.line, r.path.as_str())).collect();
    let want = [
        (2, "demo::Gian"),
        (3, "syrp_widgets_slider::Slider"),
        (3, "syrp::prelude::Thing"),
        (1, "demo::sub::Missing"),
    ];
    assert_eq!(found, want);
    assert_eq!(refs[3].file, files[1]);
    assert!(err.to_string().contains("spec.md:2: demo::Gian"), "{err}");
}
