#[test]
fn b3_front_matter_compiles_into_migration_map() {
    let slider = "---\njuce: juce::Slider\nsyrp: syrp_widgets_slider::Slider\nnotes: 'Range is inclusive.'\nstatus: todo\n---\n# Slider\n";
    let empty = "---\njuce: juce::Value\nsyrp:\nnotes: ~\n---\n";
    let blank = "---\n---\n";
    let dir = scratch(
        "migration",
        &[
            ("slider.md", slider),
            ("value.md", empty),
            ("blank.md", blank),
            ("README.md", "# Hi\n"),
        ],
    );
    let map = MigrationMap::load(&dir).unwrap();
    let sources: Vec<&str> = map.entries.iter().map(|e| e.source.as_str()).collect();
    assert_eq!(
        sources,
        ["blank.md", "slider.md", "value.md"],
        "README skipped; sorted by juce"
    );
    assert_eq!(
        map.entries[0],
        MigrationEntry {
            source: "blank.md".into(),
            ..Default::default()
        }
    );
    let s = &map.entries[1];
    assert_eq!(s.syrp.as_deref(), Some("syrp_widgets_slider::Slider"));
    assert_eq!(
        (s.notes.as_deref(), s.status.as_deref()),
        (Some("Range is inclusive."), Some("todo"))
    );
    assert_eq!(
        (&map.entries[2].syrp, &map.entries[2].notes),
        (&None, &None)
    );
    let json: serde_json::Value = serde_json::from_str(&map.to_json()).unwrap();
    assert_eq!(json["schema"], "syrp.migration-map/v1");
    assert_eq!(json["entries"][1]["juce"], "juce::Slider");
    assert!(json["entries"][2]["syrp"].is_null());
}

#[test]
fn b3_malformed_front_matter_is_doc_0005() {
    let cases = [
        ("---\njuce: a\n", "not closed"),
        ("---\njuce a\n---\n", "line 2: expected `key: value`"),
        (
            "---\nsyrp: x\nsyrp: y\n---\n",
            "line 3: `syrp` is set twice",
        ),
        ("---\nnotes: \"open\n---\n", "unterminated"),
        ("---\nwidget: x\n---\n", "unknown key `widget`"),
    ];
    for (text, want) in cases {
        let err = parse_migration_front_matter(text).unwrap_err();
        assert!(err.contains(want), "{text:?}: {err}");
    }
    let dir = scratch(
        "migration-bad",
        &[
            ("a.md", "---\njuce: juce::X\n---\n"),
            ("b.md", "---\njuce: juce::X\n---\n"),
        ],
    );
    let err = MigrationMap::load(&dir).unwrap_err();
    assert_eq!(err.code().as_str(), "SYRP-DOC-0005");
    assert!(err.to_string().contains("already mapped by a.md"), "{err}");
}

