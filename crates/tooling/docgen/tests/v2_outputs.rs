//! B3 `migration-map.json`, B4 `check-refs`. Index-based tests use `tests/fixtures/demo.json`.

use std::path::{Path, PathBuf};

use syrp_docgen::*;

fn here(rel: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(rel)
}

fn index() -> ApiIndex {
    build_index(&[here("tests/fixtures/demo.json")]).expect("fixture parses")
}

/// A fresh directory under the test target dir holding `files` (name, contents).
fn scratch(name: &str, files: &[(&str, &str)]) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("docgen-v2-{name}"));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    for (file, text) in files {
        std::fs::write(dir.join(file), text).unwrap();
    }
    dir
}

const AGENTS: &str = "# demo\n\n## Purpose\nA demo crate.\n\n## Invariants\n- Gains are linear.\n";

#[test]
fn b1_brief_has_agents_body_then_top_api_items() {
    let brief = write_crate_brief(AGENTS, &index(), "demo", BRIEF_TOKEN_BUDGET);
    assert!(
        brief.starts_with("# demo brief\n\n> GENERATED by syrp-docgen"),
        "{brief}"
    );
    assert!(brief.contains("## Purpose\nA demo crate.\n\n## Invariants\n- Gains are linear.\n"));
    assert!(!brief.contains("\n# demo\n"), "AGENTS.md title is dropped");
    let api = &brief[brief.find("## Top API").expect("api section")..];
    // Crate-level items only: types and traits first, then the rest by path; no members.
    assert!(api.contains("(demo::Gain) [alias: AudioGain, juce::dsp::Gain]: A gain stage"));
    assert!(api.find("(demo::Process)").unwrap() < api.find("(demo::add)").unwrap());
    assert!(!api.contains("demo::Gain::new") && !api.contains("demo::sub::Sample"));
    assert!(!brief.contains("omitted"));
}

#[test]
fn b1_brief_never_exceeds_its_token_budget() {
    let index = index();
    for budget in [70, 90, 120, 200] {
        let brief = write_crate_brief(AGENTS, &index, "demo", budget);
        assert!(
            brief.len().div_ceil(4) <= budget,
            "budget {budget}: {}",
            brief.len()
        );
        assert!(brief.contains("## Invariants"));
        assert!(
            brief
                .trim_end()
                .ends_with("more items omitted (token budget)"),
            "{brief}"
        );
    }
    // AGENTS.md alone too long: cut at a line, with a note, and no API list.
    let long = format!("# demo\n\n## Purpose\n{}", "A line of text.\n".repeat(400));
    let brief = write_crate_brief(&long, &index, "demo", 300);
    assert!(
        brief.len() <= 1200 && brief.ends_with("token budget.)_\n"),
        "{brief}"
    );
    assert!(!brief.contains("## Top API"));
    assert_eq!(write_crate_brief(AGENTS, &index, "demo", 5), "");
}

