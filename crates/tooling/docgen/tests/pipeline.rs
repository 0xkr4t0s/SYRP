//! End-to-end tests over `tests/fixtures/demo.json`: the rustdoc JSON of `tests/fixtures/demo`,
//! trimmed of external paths and synthetic impls (see AGENTS.md to regenerate it).

use std::path::{Path, PathBuf};

use syrp_docgen::*;

fn here(rel: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(rel)
}

fn index() -> ApiIndex {
    build_index(&[here("tests/fixtures/demo.json")]).expect("fixture parses")
}

fn entry(index: &ApiIndex, path: &str) -> ApiEntry {
    let found = index.entries.iter().find(|e| e.path == path);
    found.unwrap_or_else(|| panic!("no entry {path}")).clone()
}

#[test]
fn b1_entries_carry_summary_aliases_source_and_deprecation() {
    let index = index();
    let add = entry(&index, "demo::add");
    assert_eq!((&*add.crate_name, add.kind), ("demo", ItemKind::Function));
    assert_eq!(add.signature, "pub fn add(a: u32, b: u32) -> u32");
    assert_eq!(add.summary, "Adds two numbers.");
    assert_eq!(add.aliases, ["addNumbers"]);
    let source = add.source.expect("span");
    assert_eq!((&*source.file, source.line), ("src/lib.rs", 7));
    let gain = entry(&index, "demo::Gain");
    assert_eq!(gain.aliases, ["AudioGain", "juce::dsp::Gain"]);
    assert_eq!(gain.summary, "A gain stage over two lines.");
    assert_eq!(
        entry(&index, "demo::old_add").deprecated.as_deref(),
        Some("use `add`")
    );
    assert_eq!(add.deprecated, None);
}

#[test]
fn b1_exactly_the_public_items_are_indexed_in_order() {
    // Not here: private items, the private `hidden` module (only its re-export), the private
    // field and method of `Gain`, and `Clone for Gain` (trait impls document the trait).
    let paths: Vec<String> = index().entries.into_iter().map(|e| e.path).collect();
    let expected = "demo::COUNTER demo::Gain demo::Gain::apply demo::Gain::get demo::Gain::new \
        demo::Gain::value demo::Index demo::MAX demo::Mode demo::Mode::Custom demo::Mode::Fast \
        demo::Mode::Rate demo::Process demo::Process::CHANNELS demo::Process::Sample \
        demo::Process::process demo::Renamed demo::add demo::gain demo::old_add demo::sub \
        demo::sub::Callback demo::sub::Sample";
    assert_eq!(paths.join(" "), expected);
}

#[test]
fn b1_signatures_render_generics_and_receivers() {
    let index = index();
    let cases = [
        ("demo::Gain", "pub struct Gain<T: Copy>"),
        ("demo::Gain::get", "pub const fn get(&self) -> T"),
        ("demo::Index", "pub struct Index(pub usize)"),
        ("demo::Mode::Custom", "Custom { name: &'static str }"),
        ("demo::Process", "pub trait Process: Send"),
        (
            "demo::Process::process",
            "fn process(&mut self, buf: &mut [Self::Sample])",
        ),
        ("demo::Process::CHANNELS", "const CHANNELS: usize = 2"),
        ("demo::Process::Sample", "type Sample: Copy"),
        (
            "demo::COUNTER",
            "pub static COUNTER: std::sync::atomic::AtomicU32",
        ),
        ("demo::gain", "macro_rules! gain"),
        ("demo::Renamed", "pub struct Renamed"),
        (
            "demo::sub::Callback",
            "pub type Callback = fn(&[f32]) -> Option<Box<dyn Fn(f32) -> f32 + Send>>",
        ),
        (
            "demo::Gain::apply",
            "pub fn apply<'s, I>(&mut self, items: impl IntoIterator<Item = &'s mut f32>, _extra: I) where I: Clone + Send",
        ),
    ];
    for (path, signature) in cases {
        assert_eq!(entry(&index, path).signature, signature);
    }
    assert_eq!(entry(&index, "demo::Gain::apply").kind, ItemKind::Method);
}

