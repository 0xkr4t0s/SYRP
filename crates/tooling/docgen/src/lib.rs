//! `syrp-docgen`: the agent-facing docs pipeline (master plan §13.1).
//!
//! Reads rustdoc JSON (via [`rustdoc_types`]) and turns it into `api-index.json`, a flat list
//! of every public item with its path, kind, signature, first doc paragraph, `doc(alias)`
//! values (JUCE names) and source location. The index can be searched offline ([`search`])
//! or cut into per-crate `llms-<crate>.txt` slices sized to a token budget
//! ([`write_crate_slice`]).

mod error;
mod extract;
mod render;
mod search;
mod slice;
mod toolchain;

use std::path::{Path, PathBuf};

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

pub use error::DocError;
pub use extract::index_crate;
pub use search::{SearchHit, search};
pub use slice::write_crate_slice;
pub use syrp_error::{Diagnostic, ErrorCode};
pub use toolchain::{NightlyToolchain, detect_nightly, generate_rustdoc_json};

/// The `schema` tag written into every `api-index.json`.
const API_INDEX_SCHEMA_ID: &str = "syrp.api-index/v1";

/// The rustdoc JSON format version this crate reads (from the pinned `rustdoc-types`).
///
/// ```
/// assert!(syrp_docgen::RUSTDOC_FORMAT_VERSION > 0);
/// ```
pub const RUSTDOC_FORMAT_VERSION: u32 = rustdoc_types::FORMAT_VERSION;

/// The whole `api-index.json` document.
///
/// ```
/// let index = syrp_docgen::ApiIndex::new(Vec::new());
/// assert_eq!(index.schema, "syrp.api-index/v1");
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ApiIndex {
    /// Always `syrp.api-index/v1`.
    pub schema: String,
    /// Marks the file as generated: `GENERATED by syrp-docgen <version>. Do not edit.`
    pub generated: String,
    /// The rustdoc JSON format version the index was built from.
    pub rustdoc_format_version: u32,
    /// One entry per public item, sorted by `crate_name`, `path`, then `kind`.
    pub entries: Vec<ApiEntry>,
}

impl ApiIndex {
    /// Sorts and dedups `entries` and wraps them in a document with the current header.
    ///
    /// ```
    /// assert!(syrp_docgen::ApiIndex::new(vec![]).generated.starts_with("GENERATED"));
    /// ```
    pub fn new(mut entries: Vec<ApiEntry>) -> Self {
        entries.sort_by_key(|e| (e.crate_name.clone(), e.path.clone(), e.kind));
        entries.dedup();
        let version = env!("CARGO_PKG_VERSION");
        let generated = format!("GENERATED by syrp-docgen {version}. Do not edit.");
        let (schema, rustdoc_format_version) = (API_INDEX_SCHEMA_ID.into(), RUSTDOC_FORMAT_VERSION);
        Self {
            schema,
            generated,
            rustdoc_format_version,
            entries,
        }
    }

    /// Serialises the index as pretty JSON with a trailing newline (the committed form).
    ///
    /// ```
    /// assert!(syrp_docgen::ApiIndex::new(vec![]).to_json().ends_with("}\n"));
    /// ```
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("ApiIndex always serialises") + "\n"
    }
}

/// One public item in the index.
///
/// ```
/// let index = syrp_docgen::ApiIndex::new(vec![]);
/// assert!(index.entries.iter().all(|e: &syrp_docgen::ApiEntry| !e.signature.is_empty()));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ApiEntry {
    /// The crate the item is documented in, with `-` replaced by `_`.
    pub crate_name: String,
    /// Full path, for example `syrp_core::Gain::new`.
    pub path: String,
    /// What kind of item this is.
    pub kind: ItemKind,
    /// One-line Rust declaration, without the body.
    pub signature: String,
    /// The first paragraph of the doc comment, joined onto one line. Empty when undocumented.
    pub summary: String,
    /// `#[doc(alias = "...")]` values; JUCE names live here.
    pub aliases: Vec<String>,
    /// The deprecation note (or `since` version) when the item is `#[deprecated]`.
    pub deprecated: Option<String>,
    /// Where the item is defined, when rustdoc knows.
    pub source: Option<SourceLocation>,
}

/// A file and 1-based line, relative to the crate's manifest directory as rustdoc reports it.
///
/// ```
/// let s = syrp_docgen::SourceLocation { file: "src/lib.rs".into(), line: 7 };
/// assert_eq!(s.line, 7);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct SourceLocation {
    /// Path of the source file, with `/` separators.
    pub file: String,
    /// 1-based line of the item's first token.
    pub line: usize,
}

/// Kinds of indexed item, serialised in `snake_case`.
///
/// ```
/// let json = serde_json::to_string(&syrp_docgen::ItemKind::AssocType).unwrap();
/// assert_eq!(json, "\"assoc_type\"");
/// ```
#[rustfmt::skip]
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[derive(Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
#[allow(missing_docs)] // Variant names are the Rust item kinds they say.
pub enum ItemKind {
    Module, Struct, Union, Enum, Variant, Field, Function, Method, Trait, TraitAlias,
    TypeAlias, Constant, Static, AssocConst, AssocType, Macro, ProcMacro, ExternType,
}

/// Returns the JSON Schema of `api-index.json` (B2), generated with `schemars`.
///
/// It is meant to be committed as `docs/agents/api-index.schema.json`.
///
/// ```
/// assert_eq!(syrp_docgen::api_index_schema()["title"], "ApiIndex");
/// ```
pub fn api_index_schema() -> serde_json::Value {
    let schema = schemars::SchemaGenerator::default().into_root_schema_for::<ApiIndex>();
    serde_json::to_value(schema).expect("a JSON Schema always serialises")
}

/// Reads and parses one rustdoc JSON file, checking its format version first.
///
/// Errors: [`DocError::FormatVersion`] (SYRP-DOC-0002) for JSON from a nightly with another
/// format; [`DocError::Read`] (SYRP-DOC-0003) when the file is unreadable or not rustdoc JSON.
///
/// ```
/// use syrp_docgen::Diagnostic;
/// let err = syrp_docgen::load_rustdoc_json("no/such/file.json".as_ref()).unwrap_err();
/// assert_eq!(err.code().as_str(), "SYRP-DOC-0003");
/// ```
pub fn load_rustdoc_json(path: &Path) -> Result<rustdoc_types::Crate, DocError> {
    #[derive(Deserialize)]
    struct Probe {
        format_version: u32,
    }
    let path = path.to_path_buf();
    let read_err = |detail: String| DocError::Read {
        path: path.clone(),
        detail,
    };
    let text = std::fs::read_to_string(&path).map_err(|e| read_err(e.to_string()))?;
    let probe: Probe = serde_json::from_str(&text).map_err(|e| read_err(e.to_string()))?;
    if probe.format_version != RUSTDOC_FORMAT_VERSION {
        let (found, expected) = (probe.format_version, RUSTDOC_FORMAT_VERSION);
        return Err(DocError::FormatVersion {
            path,
            found,
            expected,
        });
    }
    serde_json::from_str(&text).map_err(|e| read_err(e.to_string()))
}

/// Builds the index from rustdoc JSON files, one per crate (B1).
///
/// ```
/// assert!(syrp_docgen::build_index(&[]).unwrap().entries.is_empty());
/// ```
pub fn build_index(json_files: &[PathBuf]) -> Result<ApiIndex, DocError> {
    let mut entries = Vec::new();
    for file in json_files {
        entries.extend(index_crate(&load_rustdoc_json(file)?));
    }
    Ok(ApiIndex::new(entries))
}
