//! Migration map scaffold (B3): `docs/migration/*.md` front matter to `migration-map.json`.

use std::path::Path;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::DocError;

/// The `schema` tag written into every `migration-map.json`.
const MIGRATION_SCHEMA_ID: &str = "syrp.migration-map/v1";

/// The front matter keys a migration page may use.
const KEYS: [&str; 4] = ["juce", "syrp", "notes", "status"];

/// The whole `migration-map.json` document.
///
/// ```
/// let map = syrp_docgen::MigrationMap::default();
/// assert!(map.to_json().contains("syrp.migration-map/v1"));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct MigrationMap {
    /// Always `syrp.migration-map/v1`.
    pub schema: String,
    /// Marks the file as generated: `GENERATED by syrp-docgen <version>. Do not edit.`
    pub generated: String,
    /// One entry per page with front matter, sorted by `juce`, then `source`.
    pub entries: Vec<MigrationEntry>,
}

impl Default for MigrationMap {
    fn default() -> Self {
        Self {
            schema: MIGRATION_SCHEMA_ID.into(),
            generated: crate::generated_header(),
            entries: Vec::new(),
        }
    }
}

/// One JUCE symbol and where it went. Every field may be empty (`None`) in a scaffold entry.
///
/// ```
/// let e = syrp_docgen::parse_migration_front_matter("---\njuce: juce::Slider\nsyrp:\n---\n")
///     .unwrap()
///     .unwrap();
/// assert_eq!(e.juce.as_deref(), Some("juce::Slider"));
/// assert_eq!(e.syrp, None);
/// ```
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct MigrationEntry {
    /// The JUCE symbol, for example `juce::Slider`.
    pub juce: Option<String>,
    /// The Rust item that replaces it, for example `syrp_widgets_slider::Slider`.
    pub syrp: Option<String>,
    /// A pattern note or pitfalls, on one line.
    pub notes: Option<String>,
    /// Progress marker such as `todo` or `done`.
    pub status: Option<String>,
    /// The page the entry came from, relative to the scanned directory, with `/` separators.
    pub source: String,
}

impl MigrationMap {
    /// Compiles every `*.md` page in `dir` (the repository's `docs/migration/`) into the map.
    ///
    /// Pages without front matter (such as `README.md`) are skipped. Errors:
    /// [`DocError::Migration`] (SYRP-DOC-0005) when the directory or a page cannot be read,
    /// front matter is malformed, or two pages name the same `juce` symbol.
    ///
    /// ```
    /// use syrp_docgen::{Diagnostic, MigrationMap};
    /// let err = MigrationMap::load("no/such/dir".as_ref()).unwrap_err();
    /// assert_eq!(err.code().as_str(), "SYRP-DOC-0005");
    /// ```
    pub fn load(dir: &Path) -> Result<Self, DocError> {
        let fail = |path: &Path, detail: String| DocError::Migration {
            path: path.to_path_buf(),
            detail,
        };
        let mut pages: Vec<_> = std::fs::read_dir(dir)
            .map_err(|e| fail(dir, e.to_string()))?
            .filter_map(Result::ok)
            .map(|d| d.path())
            .filter(|p| p.extension().is_some_and(|x| x == "md"))
            .collect();
        pages.sort();
        let mut entries: Vec<MigrationEntry> = Vec::new();
        for page in &pages {
            let text = std::fs::read_to_string(page).map_err(|e| fail(page, e.to_string()))?;
            let Some(mut entry) = parse_migration_front_matter(&text).map_err(|d| fail(page, d))?
            else {
                continue;
            };
            let name = page.strip_prefix(dir).unwrap_or(page);
            entry.source = name.to_string_lossy().replace('\\', "/");
            if let Some(juce) = &entry.juce
                && let Some(other) = entries.iter().find(|e| e.juce.as_ref() == Some(juce))
            {
                let detail = format!("`{juce}` is already mapped by {}", other.source);
                return Err(fail(page, detail));
            }
            entries.push(entry);
        }
        entries.sort_by(|a, b| (&a.juce, &a.source).cmp(&(&b.juce, &b.source)));
        Ok(Self {
            entries,
            ..Self::default()
        })
    }

    /// Serialises the map as pretty JSON with a trailing newline (`migration-map.json`).
    ///
    /// ```
    /// assert!(syrp_docgen::MigrationMap::default().to_json().ends_with("}\n"));
    /// ```
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("MigrationMap always serialises") + "\n"
    }
}

/// Parses a page's front matter: a first line `---`, then `key: value` lines, then `---`.
///
/// Returns `Ok(None)` when the page has no front matter. Keys are `juce`, `syrp`, `notes` and
/// `status`; each may appear once. Values are single-line strings, optionally wrapped in
/// matching `"` or `'` quotes; an empty value (or `~`, `null`) is `None`. Blank lines and `#`
/// comment lines are ignored. `source` is left empty. On error, returns a message naming the
/// 1-based line.
///
/// ```
/// use syrp_docgen::parse_migration_front_matter as parse;
/// let e = parse("---\njuce: juce::Slider\nnotes: \"Range is a RangeInclusive.\"\n---\n# Slider\n")
///     .unwrap()
///     .unwrap();
/// assert_eq!(e.notes.as_deref(), Some("Range is a RangeInclusive."));
/// assert_eq!(parse("# No front matter\n"), Ok(None));
/// assert!(parse("---\nwidget: x\n---\n").unwrap_err().contains("line 2"));
/// ```
pub fn parse_migration_front_matter(text: &str) -> Result<Option<MigrationEntry>, String> {
    let mut lines = text.lines().enumerate();
    match lines.next() {
        Some((_, first)) if first.trim_end() == "---" => {}
        _ => return Ok(None),
    }
    let mut entry = MigrationEntry::default();
    let mut seen: Vec<&str> = Vec::new();
    for (i, line) in lines {
        let n = i + 1;
        let line = line.trim();
        if line == "---" {
            return Ok(Some(entry));
        }
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = line
            .split_once(':')
            .ok_or_else(|| format!("line {n}: expected `key: value`"))?;
        let key = key.trim();
        let Some(&key) = KEYS.iter().find(|k| **k == key) else {
            return Err(format!(
                "line {n}: unknown key `{key}` (use {})",
                KEYS.join(", ")
            ));
        };
        if seen.contains(&key) {
            return Err(format!("line {n}: `{key}` is set twice"));
        }
        seen.push(key);
        let value = unquote(value.trim()).map_err(|d| format!("line {n}: {d}"))?;
        let value = (!matches!(value, "" | "~" | "null")).then(|| value.to_owned());
        match key {
            "juce" => entry.juce = value,
            "syrp" => entry.syrp = value,
            "notes" => entry.notes = value,
            _ => entry.status = value,
        }
    }
    Err("front matter is not closed by a `---` line".into())
}

/// Strips one pair of matching quotes; rejects an unmatched opening quote.
fn unquote(v: &str) -> Result<&str, String> {
    for q in ['"', '\''] {
        if let Some(rest) = v.strip_prefix(q) {
            return rest
                .strip_suffix(q)
                .ok_or_else(|| format!("unterminated {q} quote"));
        }
    }
    Ok(v)
}
