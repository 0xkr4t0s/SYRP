//! Per-crate agent briefs (B1): the crate's `AGENTS.md` plus its top API items, in budget.

use crate::ApiIndex;
use crate::slice::{entry_line, omitted, rank};

/// The default brief budget in tokens (master plan §13.1: "at most about 1,500 tokens").
///
/// ```
/// assert_eq!(syrp_docgen::BRIEF_TOKEN_BUDGET, 1500);
/// ```
pub const BRIEF_TOKEN_BUDGET: usize = 1500;

const TRUNCATED: &str = "\n_(AGENTS.md truncated to fit the token budget.)_\n";
const API_HEADING: &str = "\n## Top API\n\n";

/// Builds the agent brief for `crate_name` from its `AGENTS.md` text and the API index.
///
/// Tokens are approximated as bytes / 4 (rounded up) and the result never exceeds
/// `token_budget * 4` bytes. Layout: `# <crate> brief`, a `GENERATED` blockquote, the
/// `AGENTS.md` body (its own `#` title line dropped), then `## Top API` listing the crate-level
/// items (modules, types and traits first, then functions and the rest, by path), one line each
/// as in `llms-<crate>.txt`. Items that do not fit are counted in a final "omitted" line. If the
/// `AGENTS.md` body alone is too long, it is cut at a line boundary with a note and no API
/// list follows. Returns an empty string if even the title does not fit.
///
/// ```
/// use syrp_docgen::{ApiEntry, ApiIndex, ItemKind, write_crate_brief};
/// let e = ApiEntry { crate_name: "demo".into(), path: "demo::add".into(), kind: ItemKind::Function,
///     signature: "pub fn add(a: u32, b: u32) -> u32".into(), summary: "Adds.".into(),
///     aliases: vec![], deprecated: None, source: None };
/// let agents = "# demo\n\n## Purpose\nAdds numbers.\n";
/// let brief = write_crate_brief(agents, &ApiIndex::new(vec![e]), "demo", 1500);
/// assert!(brief.contains("## Purpose\nAdds numbers."));
/// assert!(brief.contains("- `pub fn add(a: u32, b: u32) -> u32` (demo::add): Adds.\n"));
/// ```
pub fn write_crate_brief(
    agents_md: &str,
    index: &ApiIndex,
    crate_name: &str,
    token_budget: usize,
) -> String {
    let max_bytes = token_budget.saturating_mul(4);
    let mut out = format!(
        "# {crate_name} brief\n\n> GENERATED by syrp-docgen from AGENTS.md and api-index.json. Do not edit.\n\n"
    );
    if out.len() > max_bytes {
        return String::new();
    }
    let body = agents_body(agents_md);
    if out.len() + body.len() + API_HEADING.len() > max_bytes {
        for line in body.split_inclusive('\n') {
            if out.len() + line.len() + TRUNCATED.len() > max_bytes {
                break;
            }
            out.push_str(line);
        }
        if out.len() + TRUNCATED.len() <= max_bytes {
            out.push_str(TRUNCATED);
        }
        return out;
    }
    out.push_str(&body);
    out.push_str(API_HEADING);

    let key = crate_name.replace('-', "_");
    let mut items: Vec<_> = index
        .entries
        .iter()
        .filter(|e| e.crate_name == key && e.path.matches("::").count() == 1)
        .collect();
    items.sort_by_key(|e| (rank(e.kind, &e.path), e.path.clone()));
    for (n, e) in items.iter().enumerate() {
        let line = entry_line(e);
        let rest = items.len() - n - 1;
        let reserve = if rest == 0 { 0 } else { omitted(rest).len() };
        if out.len() + line.len() + reserve > max_bytes {
            let footer = omitted(rest + 1);
            if out.len() + footer.len() <= max_bytes {
                out.push_str(&footer);
            }
            break;
        }
        out.push_str(&line);
    }
    out
}

/// The `AGENTS.md` text without its leading `# title` line, trimmed, ending in one newline.
fn agents_body(agents_md: &str) -> String {
    let text = agents_md.trim_start();
    let text = match text.strip_prefix("# ") {
        Some(rest) => rest.split_once('\n').map_or("", |(_, body)| body),
        None => text,
    };
    let text = text.trim();
    if text.is_empty() {
        String::new()
    } else {
        format!("{text}\n")
    }
}
