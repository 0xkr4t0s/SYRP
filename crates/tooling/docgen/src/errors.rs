//! Error catalogue outputs (B2): one Markdown page per domain and `errors.json` for agents.

use std::path::Path;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use syrp_error::catalogue::{self, Entry};

use crate::DocError;

/// The `schema` tag written into every `errors.json`.
const ERRORS_SCHEMA_ID: &str = "syrp.errors/v1";

/// The whole `errors.json` document: every catalogued code with its cause and fix.
///
/// ```
/// let cat = syrp_docgen::ErrorCatalogue::default();
/// assert!(cat.to_json().contains("syrp.errors/v1"));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ErrorCatalogue {
    /// Always `syrp.errors/v1`.
    pub schema: String,
    /// Marks the file as generated: `GENERATED by syrp-docgen <version>. Do not edit.`
    pub generated: String,
    /// One record per code, sorted by code.
    pub errors: Vec<ErrorRecord>,
}

impl Default for ErrorCatalogue {
    fn default() -> Self {
        Self {
            schema: ERRORS_SCHEMA_ID.into(),
            generated: crate::generated_header(),
            errors: Vec::new(),
        }
    }
}

/// One catalogued error code, as `errors.json` lists it.
///
/// ```
/// let r: &[syrp_docgen::ErrorRecord] = &syrp_docgen::ErrorCatalogue::default().errors;
/// assert!(r.is_empty());
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ErrorRecord {
    /// The code, for example `SYRP-DOC-0001`.
    pub code: String,
    /// The domain part of the code, for example `DOC`.
    pub domain: String,
    /// A short title.
    pub title: String,
    /// `error`, `warning` or `info`.
    pub severity: String,
    /// Why it happens.
    pub cause: String,
    /// How to fix it.
    pub fix: String,
    /// An optional worked example.
    pub example: Option<String>,
    /// The code's page on the human docs site.
    pub docs_url: String,
}

impl ErrorCatalogue {
    /// Reads every `*.toml` file in `dir` (the repository's `errors/`), in file-name order.
    ///
    /// Errors: [`DocError::Catalogue`] (SYRP-DOC-0004) when the directory or a file cannot be
    /// read, a file does not parse, or a code appears in two files.
    ///
    /// ```
    /// use syrp_docgen::{Diagnostic, ErrorCatalogue};
    /// let err = ErrorCatalogue::load("no/such/dir".as_ref()).unwrap_err();
    /// assert_eq!(err.code().as_str(), "SYRP-DOC-0004");
    /// ```
    pub fn load(dir: &Path) -> Result<Self, DocError> {
        let fail = |path: &Path, detail: String| DocError::Catalogue {
            path: path.to_path_buf(),
            detail,
        };
        let mut files: Vec<_> = std::fs::read_dir(dir)
            .map_err(|e| fail(dir, e.to_string()))?
            .filter_map(Result::ok)
            .map(|d| d.path())
            .filter(|p| p.extension().is_some_and(|x| x == "toml"))
            .collect();
        files.sort();
        let mut entries = Vec::new();
        for file in &files {
            let text = std::fs::read_to_string(file).map_err(|e| fail(file, e.to_string()))?;
            let parsed = catalogue::parse(&text).map_err(|e| {
                use syrp_error::Diagnostic as _;
                fail(file, format!("{}: {e}", e.code()))
            })?;
            for entry in parsed {
                if entries
                    .iter()
                    .any(|(_, e): &(_, Entry)| e.code == entry.code)
                {
                    return Err(fail(
                        file,
                        format!("{} is also in another file", entry.code),
                    ));
                }
                entries.push((file.clone(), entry));
            }
        }
        Ok(Self::from_entries(entries.into_iter().map(|(_, e)| e)))
    }

    /// Builds the catalogue from parsed entries, sorting them by code.
    ///
    /// ```
    /// let entries = syrp_error::catalogue::parse(r#"
    ///     [[error]]
    ///     code = "SYRP-RT-0001"
    ///     title = "Queue full"
    ///     severity = "error"
    ///     cause = "c"
    ///     fix = "f"
    /// "#).unwrap();
    /// let cat = syrp_docgen::ErrorCatalogue::from_entries(entries);
    /// assert_eq!(cat.errors[0].docs_url, "https://docs.syrp.dev/errors/SYRP-RT-0001");
    /// ```
    pub fn from_entries(entries: impl IntoIterator<Item = Entry>) -> Self {
        let mut errors: Vec<ErrorRecord> = entries
            .into_iter()
            .map(|e| ErrorRecord {
                domain: e.domain().to_owned(),
                docs_url: format!("{}{}", syrp_error::DOCS_BASE_URL, e.code),
                severity: e.severity.as_str().to_owned(),
                code: e.code,
                title: e.title,
                cause: e.cause,
                fix: e.fix,
                example: e.example,
            })
            .collect();
        errors.sort_by(|a, b| a.code.cmp(&b.code));
        Self {
            errors,
            ..Self::default()
        }
    }

    /// Serialises the catalogue as pretty JSON with a trailing newline (`errors.json`).
    ///
    /// ```
    /// assert!(syrp_docgen::ErrorCatalogue::default().to_json().ends_with("}\n"));
    /// ```
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("ErrorCatalogue always serialises") + "\n"
    }

    /// Renders one Markdown page per domain for the human site, as `(file name, page)` pairs.
    ///
    /// File names are the lower-cased domain plus `.md` (`doc.md`), in domain order. Each page
    /// opens with a `GENERATED` comment, then the domain's entries sorted by code.
    ///
    /// ```
    /// let pages = syrp_docgen::ErrorCatalogue::default().render_pages();
    /// assert!(pages.is_empty());
    /// ```
    pub fn render_pages(&self) -> Vec<(String, String)> {
        let mut domains: Vec<&str> = self.errors.iter().map(|e| e.domain.as_str()).collect();
        domains.dedup();
        domains
            .into_iter()
            .map(|domain| {
                let entries: Vec<Entry> = self
                    .errors
                    .iter()
                    .filter(|r| r.domain == domain)
                    .map(record_to_entry)
                    .collect();
                let header = format!("<!-- {} -->\n", self.generated);
                let page = header + &catalogue::render_markdown(&entries);
                (format!("{}.md", domain.to_lowercase()), page)
            })
            .collect()
    }
}

fn record_to_entry(r: &ErrorRecord) -> Entry {
    Entry {
        code: r.code.clone(),
        title: r.title.clone(),
        severity: syrp_error::Severity::parse(&r.severity).unwrap_or(syrp_error::Severity::Error),
        cause: r.cause.clone(),
        fix: r.fix.clone(),
        example: r.example.clone(),
    }
}
