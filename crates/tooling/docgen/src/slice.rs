//! Per-crate `llms-<crate>.txt` slices, cut to a token budget (B5).

use crate::{ApiEntry, ApiIndex, ItemKind};

/// Writes the `llms-<crate>.txt` slice for `crate_name`, at most `token_budget` tokens long.
///
/// Tokens are approximated as bytes / 4 (rounded up), so the result is never longer than
/// `token_budget * 4` bytes. The layout follows llmstxt.org: an H1, a blockquote, then an
/// `## API` list with one line per item. Top-level modules, types and traits come first, then
/// everything else in path order. When the budget runs out, a final line says how many items
/// were left out. Returns an empty string if even the header does not fit.
///
/// ```
/// use syrp_docgen::{ApiEntry, ApiIndex, ItemKind, write_crate_slice};
/// let e = ApiEntry { crate_name: "demo".into(), path: "demo::add".into(), kind: ItemKind::Function,
///     signature: "pub fn add(a: u32, b: u32) -> u32".into(), summary: "Adds.".into(),
///     aliases: vec![], deprecated: None, source: None };
/// let text = write_crate_slice(&ApiIndex::new(vec![e]), "demo", 200);
/// assert!(text.starts_with("# demo\n"));
/// assert!(text.len() <= 200 * 4);
/// ```
pub fn write_crate_slice(index: &ApiIndex, crate_name: &str, token_budget: usize) -> String {
    let max_bytes = token_budget.saturating_mul(4);
    let crate_name = crate_name.replace('-', "_");
    let mut entries: Vec<_> = index
        .entries
        .iter()
        .filter(|e| e.crate_name == crate_name)
        .collect();
    entries.sort_by_key(|e| (rank(e.kind, &e.path), e.path.clone()));

    let mut out = format!(
        "# {crate_name}\n\n> GENERATED by syrp-docgen from api-index.json. Public API of `{crate_name}`, \
         {} items.\n\n## API\n\n",
        entries.len()
    );
    if out.len() > max_bytes {
        return String::new();
    }
    for (written, e) in entries.iter().enumerate() {
        let line = entry_line(e);
        let remaining = entries.len() - written - 1;
        let footer = omitted(remaining + 1);
        // Keep room for the "omitted" footer unless this is the last entry.
        let reserve = if remaining == 0 {
            0
        } else {
            omitted(remaining).len()
        };
        if out.len() + line.len() + reserve > max_bytes {
            if out.len() + footer.len() <= max_bytes {
                out.push_str(&footer);
            }
            return out;
        }
        out.push_str(&line);
    }
    out
}

/// One `- `signature` (path) [alias: ...]: summary` list line, newline included.
pub(crate) fn entry_line(e: &ApiEntry) -> String {
    let mut line = format!("- `{}` ({})", e.signature, e.path);
    if !e.aliases.is_empty() {
        line.push_str(&format!(" [alias: {}]", e.aliases.join(", ")));
    }
    if !e.summary.is_empty() {
        line.push_str(": ");
        line.push_str(&e.summary);
    }
    line.push('\n');
    line
}

pub(crate) fn omitted(n: usize) -> String {
    format!("- ... {n} more items omitted (token budget)\n")
}

/// Sort rank: crate-level modules, types and traits first, then everything else.
pub(crate) fn rank(kind: ItemKind, path: &str) -> u8 {
    let top_level = path.matches("::").count() == 1;
    match kind {
        ItemKind::Module
        | ItemKind::Struct
        | ItemKind::Enum
        | ItemKind::Trait
        | ItemKind::Union
            if top_level =>
        {
            0
        }
        _ => 1,
    }
}
